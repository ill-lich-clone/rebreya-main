import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

globalThis.foundry ??= {
  utils: {
    deepClone: (value) => structuredClone(value),
    escapeHTML: (value) => String(value ?? "")
  }
};
globalThis.CONST ??= {
  DOCUMENT_OWNERSHIP_LEVELS: {
    OBSERVER: 2
  }
};

const toolDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(toolDirectory, "..");
const outputPath = resolve(repositoryRoot, "docs", "magic-item-automation-audit.md");
const { MAGIC_ITEMS } = await import("../magicItem.js");
const { buildMagicItemAutomationManifest } = await import("../scripts/data/magic-items-compendium.js");

function markdownCell(value) {
  return String(value ?? "")
    .replaceAll("|", "\\|")
    .replace(/\s+/gu, " ")
    .trim();
}

const rows = buildMagicItemAutomationManifest(MAGIC_ITEMS);
const deferredWorldRows = buildMagicItemAutomationManifest([
  { id: "world-special-dagger", name: "Особый Кинжал телепортации" },
  { id: "world-wound-potion", name: "Зелье заживления ран" },
  { id: "world-level-one-potion", name: "Зелье лечения 1-го уровня" }
]);
const counts = Object.fromEntries(["full", "partial", "manual", "deferred"]
  .map((status) => [status, rows.filter((row) => row.status === status).length]));
const lines = [
  "# Аудит автоматизации магических предметов",
  "",
  "> Generated by `node tools/generate-magic-item-automation-audit.mjs`. Изменяйте определения в `scripts/data/magic-items-compendium.js`, затем перегенерируйте этот файл.",
  "",
  `Всего: **${rows.length}**; full: **${counts.full}**; partial: **${counts.partial}**; manual: **${counts.manual}**; deferred: **${counts.deferred}**.`,
  "",
  "| Stable ID | Название | Существующая автоматизация | Предлагаемая автоматизация | Статус | Причина |",
  "| --- | --- | --- | --- | --- | --- |",
  ...rows.map((row) => `| ${[
    row.id,
    row.name,
    row.existingAutomation,
    row.proposedAutomation,
    row.status,
    row.reason
  ].map(markdownCell).join(" | ")} |`),
  "",
  "## Отложенные world-карточки вне каталога",
  "",
  "Эти три распознаваемые world-карточки намеренно не входят в 655 строк `MAGIC_ITEMS` и не изменяются embedded sync без отдельного решения.",
  "",
  "| Stable ID | Название | Статус | Причина |",
  "| --- | --- | --- | --- |",
  ...deferredWorldRows.map((row) => `| ${[
    row.id,
    row.name,
    row.status,
    row.reason
  ].map(markdownCell).join(" | ")} |`),
  ""
];

await writeFile(outputPath, lines.join("\n"), "utf8");
console.log(`Wrote ${rows.length} rows to ${outputPath}`);
